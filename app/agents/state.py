from typing import TypedDict


class AgentState(TypedDict, total=False):

    # =====================================================
    # USER QUERY
    # =====================================================

    query: str

    # =====================================================
    # ROUTING
    # =====================================================

    route: str

    # =====================================================
    # DOCUMENT CONTEXT
    # =====================================================

    selected_document: str

    document_context: bool

    # =====================================================
    # RAG CONTEXT
    # =====================================================

    context: str

    # =====================================================
    # RESPONSE
    # =====================================================

    answer: str

    sources: list

    # =====================================================
    # ERROR
    # =====================================================

    error: str